// Нормализация узбекского номера для партнёрских каналов.
//
// Проверяется ТОЛЬКО формат: 12 цифр, начинающихся с 998, либо 9 цифр
// национального номера. Код оператора намеренно не проверяется.
//
// Почему так: список кодов операторов меняется, и любой пропуск в нём
// означает, что живой покупатель не сможет купить — это хуже, чем пропустить
// опечатку. Ошибочно введённый номер отсекается сам собой: SMS на него не
// придёт, и в кошелёк по нему никто не войдёт, потому что вход в Namo Wallet
// идёт по коду из SMS. Разбор таких обращений — задача поддержки.
export function normalizeUzMobile(raw) {
  if (raw == null) return null;
  const digits = String(raw).replace(/\D/g, '');

  if (digits.length === 12 && digits.startsWith('998')) return `+${digits}`;
  if (digits.length === 9) return `+998${digits}`;

  return null; // неверная длина или чужой код страны
}

export const isUzMobile = (raw) => normalizeUzMobile(raw) !== null;
